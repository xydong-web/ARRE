def safe_pickle_load(path):
    with open(path, "rb") as f:
        data = f.read()
    bad = sorted({op.name for op, _arg, _pos in pickletools.genops(data) if op.name in RISKY_OPCODES})
    if bad:
        raise RuntimeError("refusing to unpickle %s: callable-bearing opcodes %s" % (path, bad))
    return pickle.loads(data), len(data)


def work_synga(job):
    root, key, rows = job
    cohort, method, run_tag, task, seed = key
    sp = source_paths(method, run_tag, task, seed)
    stp = os.path.join(root, sp["state"])
    st, nbytes = safe_pickle_load(stp)
    retro, memory = st["opt"]["retro"], st["dock"]["memory"]
    pos = {}
    if any(not isinstance(retro.get(r["smiles"]), str) for r in rows):
        with open(os.path.join(os.path.dirname(stp), "calls.tsv")) as f:
            next(f)
            for i, ln in enumerate(f, 1):
                pos.setdefault(ln.rstrip("\n").split("\t")[1], i)
    recs = []
    for r in rows:
        smi = r["smiles"]
        rec = {"candidate_id": r["candidate_id"], "smiles": smi}
        pf = retro.get(smi)
        if not isinstance(pf, str) or not pf:
            line_no = pos.get(smi)
            rec.update(route_status="unavailable_in_logs",
                       reason="after_last_state_checkpoint" if (line_no and line_no > st["calls_lines"]) else "missing_from_state_retro",
                       calls_tsv_line=line_no, state_calls_lines=st["calls_lines"])
            recs.append(rec)
            continue
        toks = pf.split(" ")
        okfmt = all((t[0] == "B" and t[1:].isdigit()) or (t[0] == "R" and ":" in t and t[1:].split(":", 1)[0].isdigit())
                    for t in toks)
        mem = memory.get(smi)
        score_consistent = bool(mem is not None and abs(mem[0] - float(r["vina_kcal_mol"])) <= VINA_TOL
                                and abs(mem[1] - float(r["qed"])) <= QED_TOL)
        last = toks[-1]
        root_ok = (last[0] == "R" and last[1:].split(":", 1)[1] == smi) or (last[0] == "B" and len(toks) == 1)
        rec.update(
            route_status="exported", route_format="synga_postfix_v1",
            source={"file": sp["state"], "state_key": "opt.retro"},
            postfix=pf, n_building_blocks=sum(1 for t in toks if t[0] == "B"), n_reactions=sum(1 for t in toks if t[0] == "R"),
            route_ambiguous=False,
            checks={"smiles_match": True, "score_consistent": score_consistent, "postfix_format_ok": okfmt,
                    "root_product_equals_smiles": bool(root_ok) if last[0] == "R" else None})
        recs.append(rec)
    unit = {"key": list(key), "kind": "synga_state", "state": sp["state"], "state_bytes": nbytes,
            "state_mtime_utc": iso_mtime(stp), "state_sha256": sha256_file(stp), "retro_entries": len(retro),
            "calls_lines": st.get("calls_lines")}
    return key, recs, unit


# --------------------------------------------------------------------------------------------
# Re-execution of SynGA / SynGBO routes with RDKit (sanity check of the index semantics)
# --------------------------------------------------------------------------------------------
_BBS, _RXNS = {}, {}


def init_reexec(bbs, smarts):
    global _BBS, _RXNS
    from rdkit import RDLogger
    from rdkit.Chem import AllChem
    RDLogger.DisableLog("rdApp.*")
    _BBS = bbs
    _RXNS = {i: AllChem.ReactionFromSmarts(s) for i, s in enumerate(smarts)}


def canon(smi, iso=True):
    from rdkit import Chem
    m = Chem.MolFromSmiles(smi)
    return None if m is None else Chem.MolToSmiles(m, isomericSmiles=iso)


def reexec_one(item):
    from rdkit import Chem
    cid, pf = item
    stack, mode = [], "exact"
    for tok in pf.split(" "):
        if tok[0] == "B":
            stack.append(_BBS[int(tok[1:])])
            continue
        rid_s, prod = tok[1:].split(":", 1)
        rxn = _RXNS[int(rid_s)]
        k = rxn.GetNumReactantTemplates()
        if len(stack) < k:
            return cid, "stack_underflow"
        args, stack = stack[-k:], stack[:-k]
        want_iso, want_flat = canon(prod, True), canon(prod, False)
        found = None
        for perm in sorted(set(itertools.permutations(range(k)))):
            mols = [Chem.MolFromSmiles(args[i]) for i in perm]
            if any(m is None for m in mols):
                continue
            try:
                outs = rxn.RunReactants(tuple(mols))
            except Exception:
                continue
            for ps in outs:
                for p in ps:
                    try:
                        Chem.SanitizeMol(p)
                    except Exception:
                        continue
                    if Chem.MolToSmiles(p) == want_iso:
                        found = "exact"
                        break
                    if found is None and Chem.MolToSmiles(p, isomericSmiles=False) == want_flat:
                        found = "flat"
                if found == "exact":
                    break
            if found == "exact":
                break
        if found is None:
            return cid, "no_match"
        if found == "flat":
            mode = "flat"
        stack.append(prod)
    return cid, (mode if len(stack) == 1 else "bad_stack")


