_ACT = re.compile(r"<GraphActionType\.(\w+)((?:,\s*-?\d*)*)\s*>")


def parse_sfn_traj(text):
    def sub(m):
        return repr((m.group(1), tuple(int(x) for x in re.findall(r"-?\d+", m.group(2)))))
    lst = ast.literal_eval(_ACT.sub(sub, text))
    return [{"step": i, "state_smiles": s, "action": [name] + list(nums)} for i, (s, (name, nums)) in enumerate(lst)]


def work_sfn(job):
    root, key, rows = job
    cohort, method, run_tag, task, seed = key
    sp = source_paths(method, run_tag, task, seed)
    dbp = os.path.join(root, sp["db"])
    hits, n_rows = scan_db(dbp, {r["smiles"] for r in rows}, False)
    recs = []
    for r in rows:
        smi = r["smiles"]
        rec = {"candidate_id": r["candidate_id"], "smiles": smi}
        e = hits.get(smi)
        if e is None:
            rec.update(route_status="unavailable_in_logs", reason="smiles_not_found_in_generated_objs_db")
            recs.append(rec)
            continue
        parsed = []
        for text, rid in e["trajs"].items():
            try:
                acts = parse_sfn_traj(text)
            except Exception:
                continue
            if acts:
                parsed.append((rid, acts))
        if not parsed:
            rec.update(route_status="unavailable_in_logs", reason="empty_or_unparseable_traj")
            recs.append(rec)
            continue
        rid0, acts0 = parsed[0]
        kinds = [a["action"][0] for a in acts0]
        rec.update(
            route_status="exported", route_format="sfn_graphaction_v1",
            source={"file": sp["db"], "db_rowid": rid0, "db_rows_same_smiles": e["n"],
                    "db_distinct_routes": len(e["trajs"])},
            n_actions=sum(1 for k_ in kinds if k_ != "Stop"),
            n_building_blocks=1 + sum(1 for k_ in kinds if k_ == "ReactBi"),
            n_reactions=sum(1 for k_ in kinds if k_ in ("ReactUni", "ReactBi")),
            actions=acts0, route_ambiguous=len(parsed) > 1,
            checks={"smiles_match": True,
                    "score_consistent": sfn_score_ok(e["fr0"], float(r["vina_kcal_mol"]), float(r["qed"])),
                    "final_state_equals_smiles": acts0[-1]["state_smiles"] == smi,
                    "starts_with_first_reactant": kinds[0] == "AddFirstReactant"})
        if len(parsed) > 1:
            rec["alt_routes"] = [{"db_rowid": rid, "actions": a} for rid, a in parsed[1:]]
        recs.append(rec)
    unit = {"key": list(key), "kind": "sfn_db", "db": sp["db"], "db_bytes": os.path.getsize(dbp),
            "db_mtime_utc": iso_mtime(dbp), "db_rows": n_rows}
    return key, recs, unit


