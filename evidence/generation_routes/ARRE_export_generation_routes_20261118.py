def now_utc():
    return dt.datetime.now(dt.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")


def iso_mtime(path):
    return dt.datetime.fromtimestamp(os.path.getmtime(path), dt.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")


def sha256_file(path, block=1 << 20):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        while True:
            b = f.read(block)
            if not b:
                break
            h.update(b)
    return h.hexdigest()


def raw_tag(run_tag):
    return run_tag[:-3] if run_tag.endswith("64k") else run_tag


def source_paths(method, run_tag, task, seed):
    if method in CGFLOW_FAMILY:
        base = "run/opt/%s/%s/seed%s" % (run_tag, task, seed)
        return {"db": base + "/train/generated_objs_0.db", "arms": base + "/rhc/arms.tsv"}
    if method == "SFN":
        base = "results/_ext/%s/%s/seed%s" % (raw_tag(run_tag), task, seed)
        return {"db": base + "/log/train/generated_objs_0.db"}
    if method in SYNGA_FAMILY:
        base = "results/_synga/%s/%s/seed%s" % (raw_tag(run_tag), task, seed)
        return {"state": base + "/state.pkl"}
    return {}


def scan_db(path, need, with_qed):
    """First-occurrence scan of results(smi, traj, fr_0[, fr_1]) for the SMILES in `need`."""
    con = sqlite3.connect("file:%s?mode=ro&immutable=1" % path, uri=True)
    try:
        q = "SELECT rowid, smi, traj, fr_0, %s FROM results" % ("fr_1" if with_qed else "NULL")
        hits, n_rows = {}, 0
        for rowid, smi, traj, fr0, fr1 in con.execute(q):
            n_rows += 1
            if smi in need:
                e = hits.get(smi)
                if e is None:
                    hits[smi] = {"rowid": rowid, "fr0": fr0, "fr1": fr1, "n": 1, "trajs": {traj: rowid}}
                else:
                    e["n"] += 1
                    e["trajs"].setdefault(traj, rowid)
        return hits, n_rows
    finally:
        con.close()


def score_ok(fr0, fr1, vina, qed, check_qed):
    if fr0 is None or abs(-10.0 * fr0 - vina) > VINA_TOL:
        return False
    if check_qed and (fr1 is None or abs(fr1 - qed) > QED_TOL):
        return False
    return True


def sfn_score_ok(fr0, vina, qed):
    """SynFlowNet stores fitness(vina, qed) = 0.5*(-0.1*min(vina,0)) + 0.5*qed, clipped to [1e-4, 100] (repo/ext/sfn_dock/dock_sfn.py)."""
    if fr0 is None:
        return False
    want = 0.5 * (-0.1 * min(vina, 0.0)) + 0.5 * qed
    return abs(min(max(want, 1e-4), 100.0) - fr0) <= 1e-3


def chain_ok(actions):
    if not actions or [a.get("step") for a in actions] != list(range(len(actions))):
        return False
    if actions[0].get("smiles") != "":
        return False
    return all(isinstance(a.get("action"), list) and len(a["action"]) == 3 for a in actions)


def parse_json_routes(trajs):
    """trajs: {traj_text: rowid} in first-seen order -> [(rowid, actions)] for parseable, non-empty routes."""
    out = []
    for text, rid in trajs.items():
        try:
            acts = json.loads(text)
        except Exception:
            continue
        if isinstance(acts, list) and acts:
            out.append((rid, acts))
    return out


