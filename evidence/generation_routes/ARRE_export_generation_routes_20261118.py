"""Export generator-recorded (generation-time) action sequences for ARRE_Selected_Molecules_20261118.

Addendum to the selected-molecule archive.  The raw run directories are read-only inputs:
  * SQLite databases are opened with mode=ro&immutable=1;
  * pickles are never executed blindly: the opcode stream is scanned first and the file is
    refused if it contains any callable-bearing opcode (GLOBAL, REDUCE, ...);
  * everything is written below --out only.

  python3 ARRE_export_generation_routes_20261118.py --root <project root> \
      --archive <dir holding selected_molecules.csv.gz> --out <output dir> [--workers 4] [--smoke]

Route sources, per generator
  B, F, FZ, RX, RXCE  run/opt/<run_tag>/<task>/seed<k>/train/generated_objs_0.db   (table results, column traj, JSON)
                      run/opt/<run_tag>/<task>/seed<k>/rhc/arms.tsv             (ARRE arm / iteration / parent elite)
  SFN                 results/_ext/<run_tag minus 64k>/<task>/seed<k>/log/train/generated_objs_0.db  (traj, Python repr)
  SynGA, SynGBO       results/_synga/<run_tag minus 64k>/<task>/seed<k>/state.pkl   (opt.retro: postfix synthesis tree)
  GA (GraphGA), S3    no synthesis route is generated by design -> status only
"""
