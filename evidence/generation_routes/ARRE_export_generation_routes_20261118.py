def dispatch(job):
    method = job[1][1]
    if method in CGFLOW_FAMILY:
        return work_cgflow(job)
    if method == "SFN":
        return work_sfn(job)
    return work_synga(job)


def write_gz_lines(path, lines):
    tmp = path + ".tmp"
    with open(tmp, "wb") as raw:
        with gzip.GzipFile(filename="", mode="wb", fileobj=raw, mtime=0, compresslevel=6) as gz:
            for ln in lines:
                gz.write(ln.encode("utf-8"))
                gz.write(b"\n")
    os.replace(tmp, path)


def write_csv_gz(path, header, rows):
    buf = io.StringIO()
    w = csv.writer(buf, lineterminator="\n")
    w.writerow(header)
    w.writerows(rows)
    tmp = path + ".tmp"
    with open(tmp, "wb") as raw:
        with gzip.GzipFile(filename="", mode="wb", fileobj=raw, mtime=0, compresslevel=6) as gz:
            gz.write(buf.getvalue().encode("utf-8"))
    os.replace(tmp, path)


def write_csv(path, header, rows):
    tmp = path + ".tmp"
    with open(tmp, "w", newline="") as f:
        w = csv.writer(f, lineterminator="\n")
        w.writerow(header)
        w.writerows(rows)
    os.replace(tmp, path)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--root", required=True, help="project root that holds run/, results/ and repo/")
    ap.add_argument("--archive", required=True, help="directory with selected_molecules.csv.gz (+ recorded_forward_paths.jsonl)")
    ap.add_argument("--out", required=True)
    ap.add_argument("--workers", type=int, default=4)
    ap.add_argument("--smoke", action="store_true", help="first unit of every (cohort, method, run_tag) only")
    a = ap.parse_args()
    t0 = time.time()
    os.makedirs(a.out, exist_ok=True)

    arc_csv = os.path.join(a.archive, "selected_molecules.csv.gz")
    arc_sha = sha256_file(arc_csv)
    with gzip.open(arc_csv, "rt", newline="") as f:
        rows = list(csv.DictReader(f))
    units = collections.OrderedDict()
    for r in rows:
        units.setdefault((r["cohort"], r["method"], r["run_tag"], r["task"], r["seed"]), []).append(r)
    jobs = []
    seen_triples = set()
    for key, rs in units.items():
        if key[1] in NOT_APPLICABLE:
            continue
        if a.smoke:
            if key[:3] in seen_triples:
                continue
            seen_triples.add(key[:3])
        jobs.append((a.root, key, rs))
    print("%s archive rows=%d units=%d jobs=%d" % (now_utc(), len(rows), len(units), len(jobs)), flush=True)

    results, unit_info = {}, []
    with Pool(a.workers) as pool:
        for i, (key, recs, unit) in enumerate(pool.imap_unordered(dispatch, jobs, chunksize=1), 1):
            results[key] = recs
            unit_info.append(unit)
            if i % 25 == 0 or i == len(jobs):
                print("%s %d/%d units, %.0fs" % (now_utc(), i, len(jobs), time.time() - t0), flush=True)

    # ---- SynGA / SynGBO: resolve building blocks, reaction SMARTS and re-execute with RDKit
    syn_recs = [rec for key, recs in results.items() if key[1] in SYNGA_FAMILY for rec in recs if rec["route_status"] == "exported"]
    catalog = {}
    if syn_recs:
        need_ids = set()
        for rec in syn_recs:
            need_ids.update(int(t[1:]) for t in rec["postfix"].split(" ") if t[0] == "B")
        blocks_path = os.path.join(a.root, SYNGA_LIB, "blocks.txt")
        rxn_path = os.path.join(a.root, SYNGA_LIB, "reactions.txt")
        with open(blocks_path) as f:
            all_blocks = f.read().splitlines()
        with open(rxn_path) as f:
            smarts = f.read().splitlines()
        bbs = {i: all_blocks[i] for i in need_ids}
        catalog = {"library": "cgflow38", "blocks_txt_lines": len(all_blocks), "reactions_txt_lines": len(smarts),
                   "blocks_txt_sha256": sha256_file(blocks_path), "reactions_txt_sha256": sha256_file(rxn_path),
                   "index_base": 0, "note": "B<i> = line i (0-based) of blocks.txt; R<j> = line j (0-based) of reactions.txt"}
        del all_blocks
        for rec in syn_recs:
            toks = rec["postfix"].split(" ")
            rec["building_blocks"] = [{"id": int(t[1:]), "smiles": bbs[int(t[1:])]} for t in toks if t[0] == "B"]
            rec["reactions"] = []
            for t in toks:
                if t[0] == "R":
                    rid, prod = t[1:].split(":", 1)
                    rec["reactions"].append({"id": int(rid), "smarts": smarts[int(rid)], "product_smiles": prod})
        with Pool(a.workers, initializer=init_reexec, initargs=(bbs, smarts)) as pool:
            out = dict(pool.imap_unordered(reexec_one, [(r["candidate_id"], r["postfix"]) for r in syn_recs], chunksize=200))
        for rec in syn_recs:
            rec["checks"]["reexecution_rdkit"] = out[rec["candidate_id"]]
        print("%s re-executed %d SynGA/SynGBO routes, %.0fs" % (now_utc(), len(syn_recs), time.time() - t0), flush=True)

    # ---- assemble in archive order
    by_id = {}
    for recs in results.values():
        for rec in recs:
            by_id[rec["candidate_id"]] = rec
    routes_lines, status_rows = [], []
    legacy_agrees = None
    for r in rows:
        cid = r["candidate_id"]
        base = [cid, r["cohort"], r["method"], r["run_tag"], r["task"], r["seed"], r["rank"]]
        if r["method"] in NOT_APPLICABLE:
            status_rows.append(base + ["not_applicable_no_route_by_design", NOT_APPLICABLE[r["method"]], "", "", "", "", "", "", "", "", "", ""])
            continue
        rec = by_id.get(cid)
        if rec is None:  # only possible with --smoke
            continue
        if rec["route_status"] != "exported":
            status_rows.append(base + [rec["route_status"], rec.get("reason", ""), "", "", "", "", "", "", "", "", "", ""])
            continue
        full = {"schema": SCHEMA}
        full.update({k: rec[k] for k in ("candidate_id", "smiles") if k in rec})
        full.update({k: v for k, v in rec.items() if k not in ("candidate_id", "smiles")})
        full["cohort"], full["method"], full["run_tag"], full["task"], full["seed"], full["rank"] = (
            r["cohort"], r["method"], r["run_tag"], r["task"], int(r["seed"]), int(r["rank"]))
        routes_lines.append(json.dumps(full, separators=(",", ":"), ensure_ascii=True))
        arre = rec.get("arre") or {}
        ck = rec["checks"]
        status_rows.append(base + [
            "exported", rec["route_format"], rec.get("n_actions", ""), rec.get("n_building_blocks", ""), rec.get("n_reactions", ""),
            int(rec["route_ambiguous"]), int(bool(ck.get("score_consistent"))),
            arre.get("arm", ""), arre.get("iteration", ""), arre.get("prefix_len", ""),
            "" if arre.get("prefix_matches_parent") is None else int(arre["prefix_matches_parent"]),
            ck.get("reexecution_rdkit", "")])

    # legacy single record cross-check
    legacy_path = os.path.join(a.archive, "recorded_forward_paths.jsonl")
    legacy = []
    if os.path.isfile(legacy_path):
        with open(legacy_path) as f:
            legacy = [json.loads(x) for x in f if x.strip()]
    legacy_report = []
    for lg in legacy:
        rec = by_id.get(lg["candidate_id"])
        legacy_report.append({"candidate_id": lg["candidate_id"],
                              "actions_equal": bool(rec and rec.get("actions") == lg["actions"]),
                              "iteration_equal": bool(rec and str((rec.get("arre") or {}).get("iteration")) == str(lg.get("iteration")))})

    hdr = ["candidate_id", "cohort", "method", "run_tag", "task", "seed", "rank", "route_status", "route_format_or_reason",
           "n_actions", "n_building_blocks", "n_reactions", "route_ambiguous", "score_consistent", "arre_arm", "arre_iteration",
           "arre_prefix_len", "arre_prefix_matches_parent", "reexecution_rdkit"]
    # route_format_or_reason: route_format for exported rows, reason for unavailable rows
    write_gz_lines(os.path.join(a.out, "generation_routes.jsonl.gz"), routes_lines)
    write_csv_gz(os.path.join(a.out, "generation_route_status.csv.gz"), hdr, status_rows)

    # ---- coverage per (cohort, method, run_tag) and arm provenance
    cov = collections.OrderedDict()
    for r in rows:
        k = (r["cohort"], r["method"], r["run_tag"])
        c = cov.setdefault(k, collections.Counter())
        c["units"] += 0
        c["selected"] += 1
        if r["method"] in NOT_APPLICABLE:
            c["not_applicable"] += 1
            continue
        rec = by_id.get(r["candidate_id"])
        if rec is None:
            continue
        if rec["route_status"] != "exported":
            c["unavailable"] += 1
            c["unavailable_after_checkpoint"] += int(rec.get("reason") == "after_last_state_checkpoint")
            continue
        c["exported"] += 1
        ck = rec["checks"]
        c["ambiguous"] += int(rec["route_ambiguous"])
        c["score_consistent"] += int(bool(ck.get("score_consistent")))
        c["chain_or_format_ok"] += int(bool(ck.get("chain_ok", ck.get("postfix_format_ok", ck.get("final_state_equals_smiles")))))
        arre = rec.get("arre")
        if arre:
            c["arre_provenance"] += 1
            c["arm_" + arre["arm"]] += 1
            if arre.get("prefix_len"):
                c["prefix_selected"] += 1
                c["prefix_verified"] += int(arre.get("prefix_matches_parent") is True)
                c["prefix_parent_not_found"] += int(arre.get("parent_found") is False)
        rx = ck.get("reexecution_rdkit")
        if rx:
            c["reexec_checked"] += 1
            c["reexec_exact"] += int(rx == "exact")
            c["reexec_flat"] += int(rx == "flat")
    for key in units:
        if not a.smoke or key[:3] in {k for k in cov}:
            cov[key[:3]]["units"] += 1
    cov_hdr = ["cohort", "method", "run_tag", "units", "selected", "exported", "not_applicable", "unavailable",
               "unavailable_after_checkpoint", "ambiguous",
               "score_consistent", "chain_or_format_ok", "arre_provenance", "arm_onpolicy", "arm_prefix1", "arm_prefix2",
               "prefix_selected", "prefix_verified", "prefix_parent_not_found", "reexec_checked", "reexec_exact", "reexec_flat"]
    write_csv(os.path.join(a.out, "coverage.csv"), cov_hdr, [list(k) + [cov[k][h] for h in cov_hdr[3:]] for k in cov])

    arm_rows = []
    base_by_triple = collections.defaultdict(collections.Counter)
    for u in unit_info:
        if u.get("arm_base"):
            base_by_triple[tuple(u["key"][:3])].update(u["arm_base"])
    for k, c in cov.items():
        b = base_by_triple.get(k)
        if not b:
            continue
        tb, ts = sum(b.values()), sum(c["arm_" + x] for x in ("onpolicy", "prefix1", "prefix2"))
        for arm in ("onpolicy", "prefix1", "prefix2"):
            sh_b = b[arm] / tb if tb else 0.0
            sh_s = c["arm_" + arm] / ts if ts else 0.0
            arm_rows.append(list(k) + [arm, b[arm], "%.6f" % sh_b, c["arm_" + arm], "%.6f" % sh_s,
                                       "%.4f" % (sh_s / sh_b) if sh_b else ""])
    write_csv(os.path.join(a.out, "arm_provenance_summary.csv"),
              ["cohort", "method", "run_tag", "arm", "n_docked_unique", "share_docked_unique", "n_selected", "share_selected",
               "enrichment_selected_over_docked"], arm_rows)

    with open(os.path.join(a.out, "raw_source_manifest.jsonl"), "w") as f:
        for u in sorted(unit_info, key=lambda x: x["key"]):
            f.write(json.dumps(u, separators=(",", ":")) + "\n")

    tot = collections.Counter()
    for c in cov.values():
        tot.update(c)
    summary = {
        "schema": SCHEMA, "generated_utc": now_utc(), "elapsed_s": round(time.time() - t0, 1), "smoke": a.smoke,
        "python": sys.version.split()[0], "platform": platform.platform(),
        "archive_selected_molecules_sha256": arc_sha, "archive_rows": len(rows), "units_total": len(units),
        "units_processed": len(unit_info), "totals": dict(tot),
        "synga_catalog": catalog, "legacy_single_record_crosscheck": legacy_report,
    }
    with open(os.path.join(a.out, "export_summary.json"), "w") as f:
        json.dump(summary, f, indent=2, sort_keys=True)
    print(json.dumps(summary["totals"], sort_keys=True), flush=True)
    print("legacy cross-check:", json.dumps(legacy_report), flush=True)
    print("%s done %.0fs" % (now_utc(), time.time() - t0), flush=True)


if __name__ == "__main__":
    main()
