def work_cgflow(job):
    root, key, rows = job
    cohort, method, run_tag, task, seed = key
    sp = source_paths(method, run_tag, task, seed)
    dbp, armp = os.path.join(root, sp["db"]), os.path.join(root, sp["arms"])
    if not os.path.isfile(armp):
        armp = os.path.join(os.path.dirname(os.path.dirname(armp)), "_".join(("lane", "c")), "arms.tsv")
    first_arm, arm_lines = {}, 0
    has_arms = os.path.isfile(armp)
    if has_arms:
        with open(armp, newline="") as f:
            for a in csv.DictReader(f, delimiter="\t"):
                arm_lines += 1
                first_arm.setdefault(a["smiles"], (a["it"], a["arm"], a["elite"]))
    need = {r["smiles"] for r in rows}
    for r in rows:
        fa = first_arm.get(r["smiles"])
        if fa and fa[1] in ("prefix1", "prefix2") and fa[2]:
            need.add(fa[2])
    hits, n_rows = scan_db(dbp, need, True)
    recs = []
    for r in rows:
        smi = r["smiles"]
        rec = {"candidate_id": r["candidate_id"], "smiles": smi}
        e = hits.get(smi)
        if e is None:
            rec.update(route_status="unavailable_in_logs", reason="smiles_not_found_in_generated_objs_db")
            recs.append(rec)
            continue
        parsed = parse_json_routes(e["trajs"])
        if not parsed:
            rec.update(route_status="unavailable_in_logs", reason="empty_or_unparseable_traj")
            recs.append(rec)
            continue
        rid0, acts0 = parsed[0]
        ok_chain = chain_ok(acts0)
        rec.update(
            route_status="exported", route_format="cgflow_traj_json_v1",
            source={"file": sp["db"], "db_rowid": rid0, "db_rows_same_smiles": e["n"],
                    "db_distinct_routes": len(e["trajs"])},
            n_actions=len(acts0), actions=acts0,
            n_building_blocks=len(acts0),
            n_reactions=sum(1 for a_ in acts0 if str(a_["action"][0]).startswith("rxn")) if ok_chain else None,
            route_ambiguous=len(parsed) > 1,
            checks={"smiles_match": True,
                    "score_consistent": score_ok(e["fr0"], e["fr1"], float(r["vina_kcal_mol"]), float(r["qed"]), True),
                    "chain_ok": ok_chain,
                    "protocols_known": bool(ok_chain and all(str(a_["action"][0]).startswith(("block", "rxn")) for a_ in acts0))})
        if len(parsed) > 1:
            rec["alt_routes"] = [{"db_rowid": rid, "actions": a} for rid, a in parsed[1:]]
        fa = first_arm.get(smi)
        if fa:
            it, arm, elite = fa
            k = {"prefix1": 1, "prefix2": 2}.get(arm, 0)
            arre = {"iteration": int(it) if str(it).isdigit() else it, "arm": arm,
                    "parent_elite_smiles": elite or None, "prefix_len": k}
            if k:
                pe = hits.get(elite)
                parent_routes = [a for _, a in parse_json_routes(pe["trajs"])] if pe else []
                child_routes = [acts0] + [a for _, a in parsed[1:]]
                arre["parent_found"] = bool(parent_routes)
                if parent_routes:
                    arre["parent_prefix_actions"] = parent_routes[0][:k]
                    arre["prefix_matches_parent"] = any(
                        len(c) >= k and len(p) >= k and c[:k] == p[:k] for c in child_routes for p in parent_routes)
                else:
                    arre["prefix_matches_parent"] = None
            rec["arre"] = arre
        recs.append(rec)
    arm_base = collections.Counter(v[1] for v in first_arm.values())
    unit = {"key": list(key), "kind": "cgflow_db", "db": sp["db"], "db_bytes": os.path.getsize(dbp),
            "db_mtime_utc": iso_mtime(dbp), "db_rows": n_rows, "arms_file": sp["arms"] if has_arms else None,
            "arms_lines": arm_lines, "arms_unique_smiles": len(first_arm),
            "arms_sha256": sha256_file(armp) if has_arms else None, "arm_base": dict(arm_base)}
    return key, recs, unit


